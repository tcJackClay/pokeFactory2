#!/usr/bin/env python3
"""Generate the factory shop's fixed Rogue expansion item-evolution relations.

The source checkout is intentionally outside this worktree. Run with
`python scripts/generate_factory_evolution_relations.py` or pass
`ROGUE_SPECIES_INFO_DIR` to point at the same pinned source used by
`docs/tasks/_gen_evolution_appendix.py`.
"""

import glob
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = Path(os.environ.get(
    "ROGUE_SPECIES_INFO_DIR",
    "D:/Games/pokeFactory2/output/rogue-expansion-reference/src/data/pokemon/species_info",
))
OUTPUT = ROOT / "src/features/game/config/factoryEvolutionRelations.generated.ts"
ITEM_SOURCE = (ROOT / "src/features/game/config/factoryEvolutionItems.ts").read_text(encoding="utf-8")
ITEM_IDS = set(re.findall(r"^  '([a-z_]+)',$", ITEM_SOURCE, re.MULTILINE))
ITEM_IDS.discard("kings_rock")

SLUG_OVERRIDES = {
    "FLORGES_": "florges",
    "FLABEBE_WHITE_FLOWER": "flabebe-white",
    "DARMANITAN_GALARIAN_STANDARD_MODE": "darmanitan-galar-standard",
    "URSHIFU_SINGLE_STRIKE_STYLE": "urshifu-single-strike",
    "URSHIFU_RAPID_STRIKE_STYLE": "urshifu-rapid-strike",
    "PORYGON2": "porygon2",
    "PORYGON_Z": "porygon-z",
}


def species_slug(symbol: str) -> str:
    stem = symbol.removeprefix("SPECIES_")
    if stem in SLUG_OVERRIDES:
        return SLUG_OVERRIDES[stem]
    stem = stem.replace("_ALOLAN", "_ALOLA").replace("_GALARIAN", "_GALAR")
    stem = stem.replace("_HISUIAN", "_HISUI")
    return stem.lower().replace("_", "-")


files = sorted(glob.glob(str(SOURCE / "gen_*.h")))
if len(files) != 9:
    raise RuntimeError(f"Expected nine pinned Rogue gen files, got {len(files)}: {SOURCE}")

rows = []
for path in files:
    blocks = re.split(r"\n\s*\[(SPECIES_[A-Z0-9_]+)\]\s*=\s*", Path(path).read_text(encoding="utf-8", errors="replace"))
    for pos in range(1, len(blocks), 2):
        source_symbol, body = blocks[pos], blocks[pos + 1]
        for kind, item, target_symbol in re.findall(
            r"\{(EVO_ITEM(?:_MALE|_FEMALE)?),\s*(ITEM_[A-Z0-9_]+),\s*(SPECIES_[A-Z0-9_]+)", body
        ):
            item_id = item.removeprefix("ITEM_").lower()
            if item_id not in ITEM_IDS:
                continue
            gender = "male" if kind == "EVO_ITEM_MALE" else "female" if kind == "EVO_ITEM_FEMALE" else None
            rows.append((item_id, species_slug(source_symbol), species_slug(target_symbol), gender, source_symbol, target_symbol))

rows = sorted(set(rows))
if len(rows) != 94 or len({row[0] for row in rows}) != 39:
    raise RuntimeError(f"Pinned Rogue relation count changed: {len(rows)} rows, {len({row[0] for row in rows})} items")

lines = [
    "// Generated by scripts/generate_factory_evolution_relations.py from pinned Rogue expansion a6adfcf18d7eaf99c2803e4b0bc04eca7af2f014.",
    "// Do not edit by hand. PokeAPI supplies species resources, never evolution eligibility.",
    "import type { FactoryEvolutionItemId } from './factoryEvolutionItems';",
    "",
    "export interface FactoryEvolutionRelation {",
    "  itemId: FactoryEvolutionItemId;",
    "  fromSlug: string;",
    "  toSlug: string;",
    "  gender: 'male' | 'female' | null;",
    "  fromSymbol: string;",
    "  toSymbol: string;",
    "}",
    "",
    "export const FACTORY_EVOLUTION_RELATIONS: readonly FactoryEvolutionRelation[] = [",
]
for item_id, source_slug, target_slug, gender, source_symbol, target_symbol in rows:
    gender_literal = "null" if gender is None else f"'{gender}'"
    lines.append(
        f"  {{ itemId: '{item_id}', fromSlug: '{source_slug}', toSlug: '{target_slug}', "
        f"gender: {gender_literal}, fromSymbol: '{source_symbol}', toSymbol: '{target_symbol}' }},"
    )
lines.append("];")
lines.append("")
generated = "\n".join(lines)
if "--check" in sys.argv:
    if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != generated:
        raise SystemExit("Generated factory evolution relations differ from pinned Rogue source")
    print(f"verified {len(rows)} relations and {len({row[0] for row in rows})} items")
else:
    OUTPUT.write_text(generated, encoding="utf-8")
    print(f"wrote {OUTPUT} ({len(rows)} relations, {len({row[0] for row in rows})} items)")
