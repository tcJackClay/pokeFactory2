#!/usr/bin/env node
// Runtime derivative of the pinned ordinary profiles. Does not grant shop admission.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const extractor = require('./extract_rogue_tm_compat.cjs');

const PROJECT_ROOT = path.resolve(__dirname, '..');
const GENERATED_PATH = 'src/features/game/data/fixedTm/generated.ts';
const PROVENANCE_PATH = 'docs/tasks/固定TM运行数据/provenance.json';
const MAPPING_DIGEST = '20d76b0c244a45edd20ee5d789c64ce467a2efe2278e2e4c193037368f8953dc';
const sha256 = (value) => crypto.createHash('sha256').update(value).digest('hex');
const projectTextSha256 = (value) => sha256(value.toString('utf8').replace(/\r\n/g, '\n'));
function assert(condition, message) { if (!condition) throw new Error(message); }

function validateMoveManifest(matrix, manifest) {
  assert(manifest?.source?.repository === matrix.source.repository &&
    manifest.source.commit === matrix.source.commit &&
    manifest.source.inputDigestSha256 === matrix.source.digestSha256 &&
    manifest.source.mappingDigestSha256 === MAPPING_DIGEST, 'TM manifest provenance mismatch');
  assert(Array.isArray(manifest.tms) && manifest.tms.length === 50, 'TM manifest must contain 50 entries');
  const seen = new Set();
  const tms = matrix.tms.map(({ tm, move }, i) => {
    const entry = manifest.tms[i];
    const moveName = move.slice(5).toLowerCase().replaceAll('_', '-');
    assert(entry?.tm === tm && entry.key === `move/${moveName}` && !seen.has(entry.key), `TM manifest identity mismatch at ${tm}`);
    seen.add(entry.key);
    return { tm, number: i + 1, moveName, sourceMove: move };
  });
  assert(sha256(manifest.tms.map(({ tm, key }) => `${tm} ${key}\n`).join('')) === MAPPING_DIGEST, 'TM manifest ordered digest mismatch');
  return tms;
}

function buildRuntimeRows(matrix, mapping, index) {
  assert(mapping.unknown.length === 0 && mapping.conflicts.length === 0, 'Unresolved factory identity mapping');
  assert(index.length === 1076 && mapping.mappings.length === index.length, 'Factory identity coverage changed');
  const identifiers = new Set();
  const pokemonIds = new Set();
  for (const row of index) {
    assert(typeof row.identifier === 'string' && row.identifier.length > 0 && !identifiers.has(row.identifier), 'Duplicate or invalid factory identifier');
    assert(Number.isInteger(row.pokemonId) && row.pokemonId > 0 && !pokemonIds.has(row.pokemonId), 'Duplicate or invalid factory pokemonId');
    assert(Number.isInteger(row.speciesId) && row.speciesId > 0, 'Invalid factory speciesId');
    identifiers.add(row.identifier);
    pokemonIds.add(row.pokemonId);
  }
  const rows = mapping.mappings.map((row) => {
    const original = index.find((entry) => entry.identifier === row.identifier);
    assert(original?.pokemonId === row.pokemonId && original?.speciesId === row.speciesId, 'Mapping identity differs from factory index');
    const source = matrix.species[row.sourceAlias];
    assert(source && source.profile === row.profile, 'Mapping source profile differs');
    const tmNumbers = source.tms.map((tm) => {
      const number = Number(tm.slice(2));
      assert(matrix.tms[number - 1]?.tm === tm, 'Unknown TM in source profile');
      return number;
    });
    assert(new Set(tmNumbers).size === tmNumbers.length, 'Duplicate TM in source profile');
    return { identifier: row.identifier, speciesId: row.speciesId, pokemonId: row.pokemonId, sourceAlias: row.sourceAlias, tmNumbers };
  }).sort((a, b) => a.pokemonId - b.pokemonId);
  assert(new Set(rows.map((row) => row.identifier)).size === index.length && new Set(rows.map((row) => row.pokemonId)).size === index.length, 'Duplicate mapped identity');
  assert(mapping.mappings.filter((row) => row.kind === 'base').length === 1025 && mapping.mappings.filter((row) => row.kind === 'form').length === 51, 'Base/form coverage changed');
  return rows;
}

function buildArtifacts(sourceRoot, projectRoot = PROJECT_ROOT) {
  const { matrix } = extractor.extract(sourceRoot);
  const indexBytes = fs.readFileSync(path.join(projectRoot, 'storage/data/factorySpeciesIndex.json'));
  const manifestBytes = fs.readFileSync(path.join(projectRoot, 'backend/config/rogue-tm-moves.json'));
  const index = JSON.parse(indexBytes);
  const mapping = extractor.mapFactorySpecies(matrix, index, sourceRoot);
  const tms = validateMoveManifest(matrix, JSON.parse(manifestBytes));
  const rows = buildRuntimeRows(matrix, mapping, index);
  const source = { ...matrix.source, runtimeGeneratorVersion: 1 };
  const generated = [
    '// Generated by scripts/generate_fixed_tm_runtime.cjs. Do not edit by hand.',
    '// Fixed source compatibility only; no TM has shop admission from this data.',
    "import type { FixedTmEntry, FixedTmIdentityRow, FixedTmSource } from './types';",
    `export const source: FixedTmSource = ${JSON.stringify(source)};`,
    `export const tms: readonly FixedTmEntry[] = ${JSON.stringify(tms)};`,
    'export const identities: readonly FixedTmIdentityRow[] = [',
    ...rows.map((row) => `  ${JSON.stringify(row)},`),
    '];',
    '',
  ].join('\n');
  const sourceFiles = ['include/constants/pokedex.h', 'include/constants/species.h', 'src/data/party_menu.h'];
  const provenance = {
    source,
    generator: 'scripts/generate_fixed_tm_runtime.cjs',
    reproduction: 'node scripts/generate_fixed_tm_runtime.cjs --source <pinned-rogue-checkout> --check',
    inputHashes: {
      projectTextNormalization: 'UTF-8 with CRLF normalized to LF; Rogue source bytes remain exact',
      rogueFiles: Object.fromEntries(sourceFiles.map((file) => [file, sha256(fs.readFileSync(path.join(sourceRoot, file)))])),
      'storage/data/factorySpeciesIndex.json': projectTextSha256(indexBytes),
      'backend/config/rogue-tm-moves.json': projectTextSha256(manifestBytes),
      'scripts/extract_rogue_tm_compat.cjs': projectTextSha256(fs.readFileSync(path.join(projectRoot, 'scripts/extract_rogue_tm_compat.cjs'))),
      'scripts/generate_fixed_tm_runtime.cjs': projectTextSha256(fs.readFileSync(path.join(projectRoot, 'scripts/generate_fixed_tm_runtime.cjs'))),
    },
    outputHashes: { [GENERATED_PATH]: sha256(generated) },
    counts: { ...matrix.counts, mappedBase: 1025, mappedForms: 51, explicitFormExceptions: mapping.exceptionCount, mappedPairs: rows.reduce((sum, row) => sum + row.tmNumbers.length, 0), admittedTms: 0 },
    gaps: { unknownIdentities: mapping.unknown, conflictingIdentities: mapping.conflicts, fixedContent: 'not-verified-by-this-task', battleEffects: 'not-verified-by-this-task', prices: 'not-approved' },
    mappings: mapping.mappings,
  };
  return new Map([[GENERATED_PATH, generated], [PROVENANCE_PATH, `${JSON.stringify(provenance, null, 2)}\n`]]);
}

function writeOrCheckArtifacts(artifacts, projectRoot, check) {
  if (check) {
    for (const [file, expected] of artifacts) {
      const fullPath = path.join(projectRoot, file);
      assert(fs.existsSync(fullPath) && fs.readFileSync(fullPath, 'utf8') === expected, `Generated artifact differs: ${file}`);
    }
    return;
  }
  for (const [file, text] of artifacts) {
    const fullPath = path.join(projectRoot, file);
    fs.mkdirSync(path.dirname(fullPath), { recursive: true });
    fs.writeFileSync(fullPath, text, 'utf8');
  }
}

function main(args) {
  const sourceIndex = args.indexOf('--source');
  assert(sourceIndex >= 0 && args[sourceIndex + 1] && !args[sourceIndex + 1].startsWith('--'), 'Pass --source <pinned Rogue checkout>');
  assert(args.every((arg, index) => index === sourceIndex || index === sourceIndex + 1 || arg === '--check'), 'Unknown generator argument');
  const artifacts = buildArtifacts(path.resolve(args[sourceIndex + 1]));
  writeOrCheckArtifacts(artifacts, PROJECT_ROOT, args.includes('--check'));
  process.stdout.write(`${args.includes('--check') ? 'Checked' : 'Generated'} ${artifacts.size} artifacts; 50 TM identities, 1076 factory identities, 0 admitted TMs.\n`);
}

if (require.main === module) main(process.argv.slice(2));
module.exports = { validateMoveManifest, buildRuntimeRows, buildArtifacts, writeOrCheckArtifacts, sha256, projectTextSha256, GENERATED_PATH, PROVENANCE_PATH };
